// Fits the pattern weights to self-play data by least squares (Buro-style, per-weight step sizes).
//   node tools/train.js --data data --prefix g0_,g1_ --iters 200 --out js/weights.js
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const { args } = require('./common');
const E = require('../js/engine.js')();

const a = args();
const dir = a.data || 'data';
const prefixes = (a.prefix || '').split(',');
const iters = +(a.iters || 200);
const minCount = +(a.mincount || 24);
const outFile = a.out || path.join(__dirname, '../js/weights.js');

// ---- load
const files = fs.readdirSync(dir).filter(f => f.endsWith('.bin') && prefixes.some(p => f.startsWith(p)));
let total = 0;
const chunks = files.map(f => { const b = fs.readFileSync(path.join(dir, f)); const x = new Int32Array(b.buffer, b.byteOffset, b.length >> 2); total += x.length / 5; return x; });
console.log(`${files.length} files, ${total} positions`);
const byStage = Array.from({ length: E.NSTAGE }, () => []);
for (const x of chunks) {
  for (let i = 0; i < x.length; i += 5) {
    const discs = E.popcnt(x[i]) + E.popcnt(x[i + 1]) + E.popcnt(x[i + 2]) + E.popcnt(x[i + 3]);
    byStage[E.stageOf(discs)].push(x, i);
  }
}

const NFE = E.NF + 1;
const canon = E.PATTERNS.map((p, i) => E.canonTable(i));
const patOfOffset = new Int32Array(E.STAGE_SIZE);    // canonical index for every absolute index
E.PATTERNS.forEach((p, pi) => { for (let k = 0; k < p.size; k++) patOfOffset[p.off + k] = p.off + canon[pi][k]; });
for (let k = 0; k < 256; k++) patOfOffset[E.MOB_OFF + k] = E.MOB_OFF + k;

const W = new Int8Array(E.NSTAGE * E.STAGE_SIZE);
const tmp = new Int32Array(NFE);
let prevW = null;
for (let stage = E.NSTAGE - 1; stage >= 0; stage--) {
  // training set: this stage and its neighbours (smoother stage transitions, more data)
  const src = [];
  for (let s = Math.max(0, stage - 1); s <= Math.min(E.NSTAGE - 1, stage + 1); s++) src.push(byStage[s]);
  const n = src.reduce((k, l) => k + l.length / 2, 0);
  if (n === 0) { if (prevW) W.set(prevW, stage * E.STAGE_SIZE); continue; }
  const idx = new Int32Array(n * NFE), y = new Float32Array(n);
  let r = 0;
  for (const list of src) {
    for (let j = 0; j < list.length; j += 2) {
      const x = list[j], i = list[j + 1];
      E.featureIndices(x[i], x[i + 1], x[i + 2], x[i + 3], tmp);
      for (let k = 0; k < NFE; k++) idx[r * NFE + k] = patOfOffset[tmp[k]];
      y[r++] = x[i + 4];
    }
  }
  const nVal = Math.floor(n / 20);                    // every 20th sample is held out
  const isVal = (i) => i % 20 === 7;
  const cnt = new Float32Array(E.STAGE_SIZE);
  for (let i = 0; i < n; i++) if (!isVal(i)) for (let k = 0; k < NFE; k++) cnt[idx[i * NFE + k]]++;
  const w = new Float32Array(E.STAGE_SIZE), g = new Float32Array(E.STAGE_SIZE);
  if (prevW) for (let k = 0; k < E.STAGE_SIZE; k++) w[k] = prevW[k] / E.EVAL_UNIT;   // warm start from the later stage
  let bestVal = Infinity, bestW = null, bad = 0;
  for (let it = 0; it < iters; it++) {
    g.fill(0);
    let se = 0, sv = 0;
    for (let i = 0; i < n; i++) {
      let p = 0; const o = i * NFE;
      for (let k = 0; k < NFE; k++) p += w[idx[o + k]];
      const e = y[i] - p;
      if (isVal(i)) { sv += Math.abs(e); continue; }
      se += Math.abs(e);
      for (let k = 0; k < NFE; k++) g[idx[o + k]] += e;
    }
    const beta = 1.2 / NFE;
    for (let k = 0; k < E.STAGE_SIZE; k++) if (cnt[k] > 0) w[k] += beta * g[k] / Math.max(cnt[k], minCount);
    const mv = sv / Math.max(1, nVal);
    if (mv < bestVal - 1e-4) { bestVal = mv; bestW = w.slice(); bad = 0; } else if (++bad >= 8) break;
    if (it % 25 === 0) console.log(`  stage ${stage} it ${it}: train MAE ${(se / (n - nVal)).toFixed(3)} val MAE ${mv.toFixed(3)}`);
  }
  const fw = bestW || w;
  const base = stage * E.STAGE_SIZE;
  for (let k = 0; k < E.STAGE_SIZE; k++) {
    const q = Math.round(fw[patOfOffset[k]] * E.EVAL_UNIT);
    W[base + k] = q > 127 ? 127 : q < -127 ? -127 : q;
  }
  prevW = W.subarray(base, base + E.STAGE_SIZE);
  console.log(`stage ${stage}: ${n} samples, val MAE ${bestVal.toFixed(3)} discs`);
}

const b64 = zlib.gzipSync(Buffer.from(W.buffer), { level: 9 }).toString('base64');
fs.writeFileSync(outFile,
  '// Pattern evaluation weights (int8, gzip, base64) - generated by tools/train.js\n' +
  '(function (r) { var d = "' + b64 + '"; if (typeof module === "object" && module.exports) module.exports = d; else r.OTHELLO_WEIGHTS = d; })(typeof self !== "undefined" ? self : this);\n');
console.log(`wrote ${outFile}: ${(b64.length / 1024).toFixed(0)} KB`);
