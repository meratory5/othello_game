// Mines practice problems for lessons.html from self-play positions.  Every legal move of a
// problem is scored by the engine (exact solve in the endgame, depth-8 search otherwise), so
// the answers shown on the page are engine-verified.
//   node tools/build_lessons.js [--per 4] [--seed 1] [--minutes 5]
const fs = require('fs');
const path = require('path');
const { rng32, makeEngine, args } = require('./common');
const a = args();
const PER = +(a.per || 4);
const E = makeEngine();
E.initTT(20);
const X = require('../js/explain.js')(E);
const rnd = rng32(+(a.seed || 1) * 977 + 5);

// concept -> { range of empties, test(best, list) }   list = [{sq, score, tags}] sorted best first
const has = (m, id) => m.tags.some(t => t.id === id);
const CONCEPTS = {
  'basics-corner': { lo: 14, hi: 44, margin: 4, test: (b) => has(b, 'corner') },
  'basics-cx': { lo: 20, hi: 46, margin: 0, test: (b, l) => !has(b, 'x-square') && !has(b, 'c-square') && l.some(m => has(m, 'x-square') && b.score - m.score >= 10) && l.length >= 5 },
  'basics-mobility': { lo: 20, hi: 48, margin: 3, test: (b) => b.tags.some(t => t.id === 'restrict' && t.weight >= 75) },
  'mid-nakawari': { lo: 24, hi: 50, margin: 3, test: (b, l) => has(b, 'nakawari') && l.some(m => has(m, 'wall')) },
  'mid-isseki': { lo: 24, hi: 50, margin: 3, test: (b) => has(b, 'isseki') && !has(b, 'nakawari') },
  'mid-tempo': { lo: 14, hi: 40, margin: 3, test: (b) => has(b, 'pass') },
  'end-count': { lo: 3, hi: 4, margin: 4, test: (b, l) => l.length >= 2 },
  'end-temadomari': { lo: 5, hi: 9, margin: 2, test: (b, l) => has(b, 'temadomari') && l.length >= 3 },
  'end-parity': { lo: 6, hi: 10, margin: 2, test: (b, l) => has(b, 'parity') && l.some(m => has(m, 'even-region') && b.score - m.score >= 4) },
};
const out = {};
for (const k in CONCEPTS) out[k] = [];
const full = () => Object.values(out).every(l => l.length >= PER);

function scoreMoves(pos, exact) {
  return E.legalMoves(pos).map((sq) => {
    const c = E.play(pos, sq);
    E.clearTT();
    const v = exact ? -E.solveExact(c) : -E.searchValue(c, 6);
    return { sq, score: v + 0, tags: X.describe(pos, sq).tags };
  }).sort((x, y) => y.score - x.score);
}

let games = 0;
const endAt = Date.now() + (+(a.minutes || 5)) * 60000;
while (!full() && Date.now() < endAt) {
  games++;
  let pos = E.initialPosition(), black = true;
  for (;;) {
    let moves = E.legalMoves(pos);
    if (!moves.length) { pos = E.passPos(pos); black = !black; moves = E.legalMoves(pos); if (!moves.length) break; }
    const empties = E.countEmpties(pos);
    // candidate concepts for this position (cheap pre-filter on the tags alone)
    if (Date.now() > endAt) break;
    const want = Object.keys(CONCEPTS).filter(k => out[k].length < PER && empties >= CONCEPTS[k].lo && empties <= CONCEPTS[k].hi);
    if (want.length && moves.length >= 2 && rnd() < (empties <= 10 ? 0.5 : 0.12)) {
      const exact = empties <= 12;
      const list = scoreMoves(pos, exact);
      const best = list[0], gap = best.score - list[1].score;
      for (const k of want) {
        const c = CONCEPTS[k];
        if (gap < c.margin || !c.test(best, list) || Math.abs(best.score) > 40) continue;
        let cells = '';
        for (let s = 0; s < 64; s++) { const v = E.cellAt(pos, s); cells += v === 0 ? '0' : (v === 1) === black ? '1' : '2'; }
        out[k].push({ cells, black, exact, moves: list.map(m => [m.sq, Math.round(m.score * 10) / 10]) });
        console.log(k, out[k].length, 'empties', empties, 'gap', gap.toFixed(1));
        break;
      }
    }
    // human-like, slightly noisy play keeps the positions natural but varied
    const r = E.think(pos, { depth: 3, noise: 3, exact: 6, rng: rnd });
    pos = E.play(pos, r.sq); black = !black;
  }
}
fs.writeFileSync(path.join(__dirname, '../js/lesson_data.js'),
  '// Practice problems for lessons.html - generated by tools/build_lessons.js\n' +
  '(function (r) { var d = ' + JSON.stringify(out) + '; if (typeof module === "object" && module.exports) module.exports = d; else r.OTHELLO_LESSON_DATA = d; })(typeof self !== "undefined" ? self : this);\n');
console.log(Object.entries(out).map(([k, l]) => k + ':' + l.length).join('  '), '| games', games);
